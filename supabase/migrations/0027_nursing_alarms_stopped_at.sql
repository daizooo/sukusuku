-- すくすく手帳: 授乳を計測し終えてから記録を保存するまでの間も「授乳中」として扱う
--
-- 「そろそろ次の授乳」(0024) は、授乳中の家族には送らないよう
-- nursing_alarms に行がある家族を対象から外している。ただしこの行は
-- ストップウォッチを止めた時点で消えていたため、
--
--   授乳する → ストップウォッチを止める → (記録を保存する前に目安の時刻が来る)
--
-- という順になると、前回の授乳が1つ前のままと見なされ、飲ませ終わったばかりなのに
-- 家族全員の端末へ「そろそろ次の授乳」が飛んでいた。記録は授乳が終わってから
-- 保存されるので、この隙間はふつうに起きる（実際に何度も起きていた）。
--
-- そこで「計測は止まっているが、まだ記録していない」状態を stopped_at で表し、
-- 記録を保存する（またはリセットする）まで行を残す。この間は
--   - 経過時間のお知らせ(send-nursing-alarms)は鳴らさない（もう飲ませていない）
--   - 「そろそろ次の授乳」(send-feeding-reminders)からは外す（授乳は済んでいる）
-- という扱いになる。
--
-- 記録せずに放置された行は send-nursing-alarms が片付ける。計測中の行は
-- これまでどおり baseline_at から90分、記録待ちの行は stopped_at から60分。
-- (飲ませ終えて1時間たっても記録が入らないなら、記録漏れとして通知を戻したほうがよい)
alter table public.nursing_alarms
  add column if not exists stopped_at timestamptz;

comment on column public.nursing_alarms.stopped_at is
  '計測を止めた時刻。記録を保存するまでの間だけ入る（null なら計測中）。この間は経過時間のお知らせは鳴らさず、「そろそろ次の授乳」からは授乳中として外す。';
