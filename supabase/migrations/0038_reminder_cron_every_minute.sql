-- すくすく手帳: お知らせの定期実行を1分おきにする
--
-- 予定・授乳の目安・検温のお知らせは、これまで5分おきに叩いていた(0013/0025/0031)。
-- そのため通知の時刻が5の倍数の分でないとぴったりには届かず、
-- 実際に「20:26の予定の通知が20:25に届いた」ことが起きた。
--
-- 5分おきだと、そのままでは時刻を最大5分過ぎてから届く。それを嫌って
-- Edge Function 側で「次の実行までの分を少し先取りする」(LOOKAHEAD_MINUTES = 1)
-- ことにしていたのが、早く届いた原因。**予定より早い通知は、遅い通知より困る。**
-- 「10分前にお知らせ」が11分前に来ると、書いてある時刻と合わなくなるため。
--
-- 叩く間隔を1分にすれば先取りが要らなくなり、どのお知らせも
-- 「その分のうちに届く（早まらない）」に揃う。先取りをやめる側の変更は
-- 同じPRで Edge Function の LOOKAHEAD_MINUTES を外して行っている。
--
-- 授乳の経過時間の片付け(0022 send-nursing-alarms)は元から1分おきで、
-- 中身は「送るものが無ければすぐ返す」形なので、回数が増えても負荷は増えない。
-- 3つのビュー(task_reminder_schedule ほか)も家族数ぶんの小さな走査で済む。

-- schedule だけを差し替える。叩く中身(net.http_post)は 0013/0025/0031 のまま。
-- ここで書き写すと、あとで URL やヘッダーを直すときに直し漏れが起きるため。
select cron.alter_job(jobid, schedule := '* * * * *')
  from cron.job
 where jobname in (
   'send-reminders',
   'send-feeding-reminders',
   'send-temperature-reminders'
 );
