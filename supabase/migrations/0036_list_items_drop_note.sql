-- ============================================================
-- list_items からメモ（note）を外す
-- ============================================================
-- リストはGoogle Keepと同じく「行にあるのは内容だけ」にした（docs/lists.md §4）。
-- 項目を押すとその場で内容を書き換えるだけで、メモの置き場が無くなったため、
-- 列ごと落とす。中身も一緒に消えるので、適用前に残しておきたいメモが無いか確かめる。
--
-- 適用はアプリ側の変更（メモを読み書きしない版）がmainに入ったあとに行う。
-- 先に落とすと、まだメモを書き込む版が動いている間、項目の更新が失敗する。
alter table public.list_items drop column if exists note;

comment on table public.list_items is
  'リストの項目。数量はタイトルに書く（「牛乳2本」）。場所はグループで表す。メモは持たない。';
